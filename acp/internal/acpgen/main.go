// Command acpgen writes Go types for the ACP v1 JSON schema.
//
// Usage: acpgen schema.json out.go
//
// Objects become structs. A union of objects tagged by a const property
// becomes a struct with one pointer per variant and its own JSON methods; any
// other union of objects is merged into one struct. Unions of strings become a
// string type with constants. Everything else is kept as json.RawMessage.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"log"
	"maps"
	"os"
	"slices"
	"strings"
)

type node struct {
	Ref                  string           `json:"$ref"`
	Description          string           `json:"description"`
	Title                string           `json:"title"`
	Type                 any              `json:"type"`
	Const                any              `json:"const"`
	Properties           map[string]*node `json:"properties"`
	Required             []string         `json:"required"`
	Items                *node            `json:"items"`
	AllOf                []*node          `json:"allOf"`
	AnyOf                []*node          `json:"anyOf"`
	OneOf                []*node          `json:"oneOf"`
	AdditionalProperties any              `json:"additionalProperties"`
	DocsIgnore           bool             `json:"x-docs-ignore"`
}

var defs map[string]*node

func main() {
	if len(os.Args) != 3 {
		log.Fatal("usage: acpgen schema.json out.go")
	}
	raw, err := os.ReadFile(os.Args[1])
	if err != nil {
		log.Fatal(err)
	}
	var schema struct {
		Defs map[string]*node `json:"$defs"`
	}
	if err := json.Unmarshal(raw, &schema); err != nil {
		log.Fatal(err)
	}
	defs = schema.Defs

	var b bytes.Buffer
	b.WriteString("// Code generated by acpgen from the ACP v1 schema. DO NOT EDIT.\n\npackage acp\n\nimport \"encoding/json\"\n\n")
	for _, n := range slices.Sorted(maps.Keys(defs)) {
		if !defs[n].DocsIgnore {
			genDef(&b, n, defs[n])
		}
	}
	b.WriteString(helpers)
	src, err := format.Source(b.Bytes())
	if err != nil {
		_ = os.WriteFile(os.Args[2], b.Bytes(), 0o644) // unformatted, to look at; the format error is the one to show
		log.Fatal(err)
	}
	if err := os.WriteFile(os.Args[2], src, 0o644); err != nil {
		log.Fatal(err)
	}
}

func variants(n *node) []*node {
	if n.OneOf != nil {
		return n.OneOf
	}
	return n.AnyOf
}

func typeName(n *node) string {
	switch t := n.Type.(type) {
	case string:
		if t != "null" {
			return t
		}
	case []any:
		for _, x := range t {
			if x != "null" {
				return x.(string) //nolint:forcetypeassert // a schema's type list holds names
			}
		}
	}
	return ""
}

func isNull(n *node) bool { return typeName(n) == "" && n.Type != nil }

func refName(n *node) string {
	if n.Ref != "" {
		return strings.TrimPrefix(n.Ref, "#/$defs/")
	}
	if len(n.AllOf) == 1 && n.Properties == nil {
		return refName(n.AllOf[0])
	}
	return ""
}

// kind classifies a definition: struct, tagged, enum, string, int, map or raw.
func kind(n *node) string {
	vs := variants(n)
	switch {
	case n.Properties != nil:
		return "struct"
	case vs != nil && allType(vs, "string"):
		return "enum"
	case vs != nil && allType(vs, "integer"):
		return "int"
	case vs != nil && tag(vs) != "":
		return "tagged"
	case vs != nil && allObjects(vs):
		return "struct"
	case typeName(n) == "string":
		return "string"
	case typeName(n) == "integer":
		return "int"
	case typeName(n) == "object":
		return "map"
	}
	return "raw"
}

func allType(vs []*node, t string) bool {
	for _, v := range vs {
		if typeName(v) != t {
			return false
		}
	}
	return true
}

func allObjects(vs []*node) bool {
	for _, v := range vs {
		r := refName(v)
		if typeName(v) != "object" && (r == "" || kind(defs[r]) != "struct") {
			return false
		}
	}
	return true
}

// tag returns the property that tells the variants apart, if there is one.
func tag(vs []*node) string {
	for _, v := range vs {
		for p, pn := range v.Properties {
			if pn.Const != nil {
				return p
			}
		}
	}
	return ""
}

// goType is the Go type of a property schema.
func goType(n *node) string {
	if r := refName(n); r != "" {
		return goName(r)
	}
	if vs := variants(n); vs != nil {
		var rest []*node
		for _, v := range vs {
			if !isNull(v) {
				rest = append(rest, v)
			}
		}
		if len(rest) == 1 {
			return goType(rest[0])
		}
		return "json.RawMessage"
	}
	switch typeName(n) {
	case "string":
		return "string"
	case "integer":
		return "int64"
	case "number":
		return "float64"
	case "boolean":
		return "bool"
	case "array":
		if n.Items == nil {
			return "[]json.RawMessage"
		}
		return "[]" + goType(n.Items)
	case "object":
		if _, typed := n.AdditionalProperties.(map[string]any); typed {
			return "json.RawMessage" // a map of typed values, kept raw to keep its order
		}
		return "map[string]any"
	}
	return "json.RawMessage"
}

type field struct {
	json, typ, doc string
	required       bool
}

// fields collects the properties of n and, merged, of its variants.
func fields(n *node, top bool, out map[string]*field, order *[]string) {
	if r := refName(n); r != "" && n.Properties == nil {
		fields(defs[r], false, out, order)
		return
	}
	for _, p := range slices.Sorted(maps.Keys(n.Properties)) {
		pn := n.Properties[p]
		t := goType(pn)
		if f, ok := out[p]; ok {
			if f.typ != t {
				f.typ = "json.RawMessage"
			}
			continue
		}
		out[p] = &field{json: p, typ: t, doc: pn.Description, required: top && slices.Contains(n.Required, p)}
		*order = append(*order, p)
	}
	for _, a := range n.AllOf {
		fields(a, top, out, order)
	}
	for _, v := range variants(n) {
		fields(v, false, out, order)
	}
}

func genDef(b *bytes.Buffer, name string, n *node) {
	gn := goName(name)
	comment(b, n.Description)
	switch kind(n) {
	case "struct":
		out := map[string]*field{}
		var order []string
		fields(n, true, out, &order)
		fmt.Fprintf(b, "type %s struct {\n", gn)
		for _, p := range order {
			f := out[p]
			t, tagOpt := f.typ, ""
			if !f.required {
				tagOpt = ",omitempty"
				if k := defKind(t); k == "struct" || k == "tagged" {
					t = "*" + t
				}
			}
			comment(b, f.doc)
			fmt.Fprintf(b, "\t%s %s `json:\"%s%s\"`\n", goName(p), t, p, tagOpt)
		}
		b.WriteString("}\n\n")
	case "enum":
		fmt.Fprintf(b, "type %s string\n\nconst (\n", gn)
		for _, v := range variants(n) {
			if c, ok := v.Const.(string); ok {
				fmt.Fprintf(b, "\t%s%s %s = %q\n", gn, goName(c), gn, c)
			}
		}
		b.WriteString(")\n\n")
	case "tagged":
		genTagged(b, gn, n)
	case "string":
		fmt.Fprintf(b, "type %s string\n\n", gn)
	case "int":
		fmt.Fprintf(b, "type %s int64\n\n", gn)
	case "map":
		fmt.Fprintf(b, "type %s map[string]any\n\n", gn)
	default:
		fmt.Fprintf(b, "type %s = json.RawMessage\n\n", gn)
	}
}

func defKind(goTyp string) string {
	for n, d := range defs {
		if goName(n) == goTyp {
			return kind(d)
		}
	}
	return ""
}

func genTagged(b *bytes.Buffer, gn string, n *node) {
	vs := variants(n)
	t := tag(vs)
	type variant struct{ value, field, typ string }
	var vars []variant
	var fallback *variant // decoded when the tag is missing or unknown
	for _, v := range vs {
		pn := v.Properties[t]
		if pn == nil {
			if r := refName(v); r != "" {
				fallback = &variant{field: goName(strings.TrimPrefix(r, gn)), typ: goName(r)}
			}
			continue
		}
		c, ok := pn.Const.(string)
		if !ok {
			continue // an open "other" variant: only the tag is kept
		}
		typ := "struct{}"
		for _, a := range v.AllOf {
			if r := refName(a); r != "" {
				typ = goName(r)
			}
		}
		vars = append(vars, variant{c, goName(c), typ})
	}
	fmt.Fprintf(b, "type %s struct {\n\t// %s is the %q tag; it picks the variant that is set.\n\t%s string\n", gn, goName(t), t, goName(t))
	for _, v := range vars {
		fmt.Fprintf(b, "\t%s *%s\n", v.field, v.typ)
	}
	if fallback != nil {
		fmt.Fprintf(b, "\t// %s is set when the tag is missing or unknown.\n\t%s *%s\n", fallback.field, fallback.field, fallback.typ)
	}
	b.WriteString("}\n\n")

	fmt.Fprintf(b, "func (u %s) MarshalJSON() ([]byte, error) {\n\tvar v any = struct{}{}\n\tswitch u.%s {\n", gn, goName(t))
	for _, v := range vars {
		fmt.Fprintf(b, "\tcase %q:\n\t\tif u.%s != nil {\n\t\t\tv = u.%s\n\t\t}\n", v.value, v.field, v.field)
	}
	if fallback != nil {
		fmt.Fprintf(b, "\tdefault:\n\t\tif u.%s != nil {\n\t\t\treturn json.Marshal(u.%s)\n\t\t}\n", fallback.field, fallback.field)
	}
	fmt.Fprintf(b, "\t}\n\treturn marshalTagged(%q, u.%s, v)\n}\n\n", t, goName(t))

	fmt.Fprintf(b, "func (u *%s) UnmarshalJSON(b []byte) error {\n\tvar t struct {\n\t\tT string `json:%q`\n\t}\n\tif err := json.Unmarshal(b, &t); err != nil {\n\t\treturn err\n\t}\n\t*u = %s{%s: t.T}\n\tswitch t.T {\n", gn, t, gn, goName(t))
	for _, v := range vars {
		fmt.Fprintf(b, "\tcase %q:\n\t\tu.%s = new(%s)\n\t\treturn json.Unmarshal(b, u.%s)\n", v.value, v.field, v.typ, v.field)
	}
	if fallback != nil {
		fmt.Fprintf(b, "\tdefault:\n\t\tu.%s = new(%s)\n\t\treturn json.Unmarshal(b, u.%s)\n\t}\n}\n\n", fallback.field, fallback.typ, fallback.field)
		return
	}
	b.WriteString("\t}\n\treturn nil\n}\n\n")
}

func comment(b *bytes.Buffer, doc string) {
	if doc == "" {
		return
	}
	for l := range strings.SplitSeq(strings.TrimSpace(doc), "\n") {
		b.WriteString(strings.TrimRight("// "+l, " ") + "\n")
	}
}

var initialisms = map[string]string{"Id": "ID", "Url": "URL", "Uri": "URI", "Mcp": "MCP", "Http": "HTTP", "Sse": "SSE", "Json": "JSON"}

// goName turns a schema name (camelCase, snake_case or _meta) into an exported Go name.
func goName(s string) string {
	var parts []string
	for _, w := range strings.FieldsFunc(s, func(r rune) bool { return r == '_' || r == '-' || r == '/' || r == '.' }) {
		start := 0
		for i := 1; i <= len(w); i++ {
			if i == len(w) || (w[i] >= 'A' && w[i] <= 'Z') {
				parts = append(parts, w[start:i])
				start = i
			}
		}
	}
	var out strings.Builder
	for _, p := range parts {
		p = strings.ToUpper(p[:1]) + p[1:]
		if r, ok := initialisms[p]; ok {
			p = r
		}
		out.WriteString(p)
	}
	return out.String()
}

const helpers = `
// marshalTagged encodes v, an object, with the tag member added first.
func marshalTagged(tag, value string, v any) ([]byte, error) {
	body, err := json.Marshal(v)
	if err != nil {
		return nil, err
	}
	head, err := json.Marshal(map[string]string{tag: value})
	if err != nil {
		return nil, err
	}
	if len(body) <= 2 {
		return head, nil
	}
	return append(head[:len(head)-1], append([]byte(","), body[1:]...)...), nil
}
`
